/**
 * Vendors the AI review core into the CLI, for `wmill review`.
 *
 * The prompt, the size budget and the reading of the model's answer are the
 * review: the deployment request panel and a pull request review must ask the
 * same thing and read the answer the same way, so both run one source,
 * frontend/src/lib/components/deploymentRequest/aiReviewCore.ts, plus the
 * folder instruction helpers it imports. The modules are concatenated as
 * TypeScript rather than bundled, so the CLI keeps their types.
 *
 * Run `bun run gen:ai-review` after touching either module;
 * test/ai_review_bundle_unit.test.ts fails when the committed copy no longer
 * matches them.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const REPO_ROOT = join(import.meta.dir, "..");
const COMPONENTS = join(REPO_ROOT, "frontend", "src", "lib", "components");
const SCOPES = join(COMPONENTS, "copilot", "chat", "folderInstructionScopes.ts");
const CORE = join(COMPONENTS, "deploymentRequest", "aiReviewCore.ts");
export const OUT_FILE = join(
  import.meta.dir,
  "src",
  "commands",
  "review",
  "aiReviewCore.gen.ts",
);

const HEADER = `// Generated by cli/generate-ai-review.ts. Do not edit.
// Run \`bun run gen:ai-review\` from cli/ to rebuild it from
// frontend/src/lib/components/deploymentRequest/aiReviewCore.ts and
// frontend/src/lib/components/copilot/chat/folderInstructionScopes.ts.
`;

const SCOPES_IMPORT =
  /^(import|export) \{[^}]*\} from '\.\.\/copilot\/chat\/folderInstructionScopes'\n/gm;

/** The vendored module, header included. Exported so the staleness test can
 * build it and compare. Line endings are normalized: a CRLF checkout is the
 * same source. */
export function buildAiReviewCore(): string {
  const read = (p: string) => readFileSync(p, "utf-8").replace(/\r\n/g, "\n");
  const scopes = read(SCOPES);
  const core = read(CORE).replace(SCOPES_IMPORT, "");
  // Anything else either module imports would not resolve in the CLI.
  for (const [file, source] of [[SCOPES, scopes], [CORE, core]]) {
    if (/^(import|export) .* from /m.test(source)) {
      throw new Error(
        `${file} imports another module. Keep the review core self-contained, ` +
          "or teach this generator to vendor what it imports.",
      );
    }
  }
  return `${HEADER}\n${scopes}\n${core}`;
}

if (import.meta.main) {
  const ts = buildAiReviewCore();
  const before = (() => {
    try {
      return readFileSync(OUT_FILE, "utf-8");
    } catch {
      return "";
    }
  })();
  writeFileSync(OUT_FILE, ts, "utf-8");
  console.log(`${before === ts ? "Unchanged" : "Wrote"} ${OUT_FILE}`);
}
