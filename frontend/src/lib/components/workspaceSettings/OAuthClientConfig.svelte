<script lang="ts">
	import type { Snippet } from 'svelte'
	import { sendUserToast } from '$lib/utils'
	import { Button, Alert } from '$lib/components/common'
	import Modal from '$lib/components/common/modal/Modal.svelte'
	import TextInput from '$lib/components/text_input/TextInput.svelte'
	import ClipboardPanel from '$lib/components/details/ClipboardPanel.svelte'
	import { ExternalLink } from 'lucide-svelte'

	interface Props {
		open?: boolean
		serviceName: string
		serviceDisplayName: string
		existingConfig?: {
			client_id: string
			client_secret: string
			base_url: string
		} | null
		redirectUri: string
		onConfigSaved: (oauthData: any) => Promise<void>
		requiresBaseUrl?: boolean
		baseUrlPlaceholder?: string
		baseUrlSettingsPath?: string
		clientIdPlaceholder?: string
		clientSecretPlaceholder?: string
		setupInstructions?: string[]
		/** Shown above the form, for what the service needs before it can be connected. */
		requirements?: Snippet
	}

	let {
		open = $bindable(false),
		serviceName,
		serviceDisplayName,
		existingConfig,
		onConfigSaved,
		redirectUri,
		requiresBaseUrl = true,
		baseUrlPlaceholder = `https://your-${serviceName}.example.com`,
		baseUrlSettingsPath = '/settings/admin/security',
		clientIdPlaceholder = `Generated by ${serviceDisplayName} OAuth app`,
		clientSecretPlaceholder = `Generated by ${serviceDisplayName} OAuth app`,
		setupInstructions,
		requirements
	}: Props = $props()

	let saving = $state(false)
	let clientId = $state('')
	let clientSecret = $state('')
	let baseUrl = $state('')

	$effect(() => {
		if (open) {
			clientId = existingConfig?.client_id ?? ''
			clientSecret = existingConfig?.client_secret ?? ''
			baseUrl = existingConfig?.base_url ?? ''
		}
	})

	const canSave = $derived(
		!saving && !!clientId.trim() && !!clientSecret.trim() && (!requiresBaseUrl || !!baseUrl.trim())
	)

	async function save() {
		if (!canSave) return
		saving = true
		try {
			await onConfigSaved({
				client_id: clientId.trim(),
				client_secret: clientSecret.trim(),
				base_url: requiresBaseUrl ? baseUrl.trim().replace(/\/+$/, '') : '',
				redirect_uri: redirectUri.trim()
			})
		} catch (err: any) {
			sendUserToast(`Failed to save the OAuth app: ${err.message}`, true)
		} finally {
			saving = false
		}
	}
</script>

<Modal
	bind:open
	title="{serviceDisplayName} OAuth app"
	description="Members connect their {serviceDisplayName} accounts through this app."
	cancelText="Cancel"
>
	<div class="flex flex-col gap-6">
		{@render requirements?.()}

		{#if !existingConfig && setupInstructions}
			<Alert type="info" title="Create an OAuth app in {serviceDisplayName}">
				<ol class="list-decimal list-inside flex flex-col gap-1">
					{#each setupInstructions as instruction}
						<li>{@html instruction}</li>
					{/each}
				</ol>
			</Alert>
		{/if}

		{#if requiresBaseUrl}
			<div class="flex flex-col gap-1">
				<div class="text-xs font-semibold text-emphasis">{serviceDisplayName} URL</div>
				<div class="text-xs text-secondary">The address of your {serviceDisplayName} server</div>
				<TextInput
					bind:value={baseUrl}
					inputProps={{ type: 'url', placeholder: baseUrlPlaceholder, disabled: saving }}
				/>
				{#if baseUrl && baseUrlSettingsPath}
					<div class="flex">
						<Button
							unifiedSize="sm"
							variant="subtle"
							href={`${baseUrl.replace(/\/+$/, '')}${baseUrlSettingsPath}`}
							target="_blank"
							startIcon={{ icon: ExternalLink }}
						>
							Open the {serviceDisplayName} OAuth settings
						</Button>
					</div>
				{/if}
			</div>
		{/if}

		<div class="flex flex-col gap-1">
			<div class="text-xs font-semibold text-emphasis">Redirect URI</div>
			<div class="text-xs text-secondary">
				Register this URL when creating the OAuth app in {serviceDisplayName}
			</div>
			<ClipboardPanel content={redirectUri} size="sm" />
		</div>

		<div class="flex flex-col gap-1">
			<div class="text-xs font-semibold text-emphasis">Client ID</div>
			<TextInput
				bind:value={clientId}
				inputProps={{ placeholder: clientIdPlaceholder, disabled: saving }}
			/>
		</div>

		<div class="flex flex-col gap-1">
			<div class="text-xs font-semibold text-emphasis">Client secret</div>
			<TextInput
				bind:value={clientSecret}
				inputProps={{ type: 'password', placeholder: clientSecretPlaceholder, disabled: saving }}
			/>
		</div>
	</div>

	{#snippet actions()}
		<Button variant="accent" disabled={!canSave} loading={saving} onclick={save}>Save</Button>
	{/snippet}
</Modal>
