-- The logins behind a data table connection made as several roles at once: one Postgres login per
-- distinct set of data table roles, a member of each. Which roles a login holds is its
-- memberships on the cluster, and its name is derived from their catalog ids, so a row only has to
-- carry the credential.
--
-- A row is written after its login exists and removed before the login is dropped, so a row always
-- names a login that can authenticate with `pwd`.
CREATE TABLE datatable_role_set (
    cluster VARCHAR(20) NOT NULL CHECK (cluster IN ('instance', 'external_instance')),
    name VARCHAR(63) NOT NULL,
    -- Generated by Windmill, never entered by anyone, and never leaves the server.
    pwd TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Recorded at most once a day. A login unused for long enough is dropped, and made again if
    -- its set of roles is asked for later.
    last_used_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (cluster, name)
);

GRANT ALL ON datatable_role_set TO windmill_user;
GRANT ALL ON datatable_role_set TO windmill_admin;
