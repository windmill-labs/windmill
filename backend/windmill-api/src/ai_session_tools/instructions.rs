//! The instructions a client receives on connecting: the session's system prompt as
//! rendered for an external client, filled in for the caller. `gen/prompt.json` holds one
//! template (`EXTERNAL_PROMPT` in the chat's `global/core.ts`) and, per access profile, the
//! flags and variables the generator computed for it: what the caller may do is decided there,
//! and only rendered here. The profile is the token's scope and, for a full token, the caller's
//! role in the workspace. The folder guidance differs per workspace, so a connection spanning
//! several workspaces gets the rest up front and each workspace's part from
//! `get_workspace_context`.

use std::collections::{HashMap, HashSet};
use std::sync::LazyLock;

use serde::Deserialize;
use windmill_common::{
    roles::{caller_capabilities, AuthorLevel, RoleCapabilities},
    workspaces::{check_deploy_rules, RuleCheckResult},
    DB,
};
use windmill_mcp::server::McpAuth;

use super::{guidance::list_skills, Ctx, SessionAccess};

/// As generated by `mcpSessionGen.test.ts`.
#[derive(Deserialize)]
struct PromptParts {
    template: String,
    profiles: HashMap<String, Profile>,
    folder_guidance: FolderGuidanceSets,
    #[cfg_attr(not(test), allow(dead_code))]
    rendered_sha256: HashMap<String, String>,
    skills_header: String,
    skill_line: String,
    workspace_instructions: String,
}

#[derive(Deserialize)]
struct Profile {
    /// The flags set, space-separated.
    flags: String,
    vars: HashMap<String, String>,
}

impl Profile {
    fn flags(&self) -> HashSet<&str> {
        self.flags.split_whitespace().collect()
    }
}

#[derive(Deserialize)]
struct FolderGuidanceSets {
    create_folder: FolderGuidance,
    no_create_folder: FolderGuidance,
}

/// The `{{folder_guidance}}` text per folder situation, with its leading newline.
#[derive(Deserialize)]
struct FolderGuidance {
    admin: String,
    admin_no_folders: String,
    member: String,
    member_no_folders: String,
    member_readonly: String,
    member_no_folders_readonly: String,
}

static PARTS: LazyLock<PromptParts> = LazyLock::new(|| {
    serde_json::from_str(include_str!("gen/prompt.json")).expect("gen/prompt.json is valid")
});

/// `promptTemplate.ts`'s grammar, which this must render identically (the generator's
/// `rendered_sha256` pins it): `{{#flag}}…{{/flag}}` keeps its body when the flag is set,
/// `{{^flag}}…{{/flag}}` when it is not, `{{name}}` takes a variable, and a variable not given
/// stays as written for a later pass to fill.
fn render_template(
    template: &str,
    flags: &HashSet<&str>,
    vars: &HashMap<String, String>,
) -> String {
    let mut out = String::with_capacity(template.len());
    // Each open section, and whether it keeps its body.
    let mut open: Vec<(&str, bool)> = Vec::new();
    let mut rest = template;
    while let Some(start) = rest.find("{{") {
        let keeping = open.iter().all(|(_, keep)| *keep);
        let Some(tag) = rest[start + 2..]
            .find("}}")
            .map(|end| &rest[start + 2..start + 2 + end])
        else {
            break;
        };
        let (kind, name) = match tag.as_bytes().first() {
            Some(b'#' | b'^' | b'/') => (Some(tag.as_bytes()[0]), &tag[1..]),
            _ => (None, tag),
        };
        if name.is_empty() || !name.bytes().all(|b| b.is_ascii_lowercase() || b == b'_') {
            // Not a tag: keep the first brace as text, as the regex there scans on.
            if keeping {
                out.push_str(&rest[..start + 1]);
            }
            rest = &rest[start + 1..];
            continue;
        }
        if keeping {
            out.push_str(&rest[..start]);
        }
        let whole = &rest[start..start + 4 + tag.len()];
        rest = &rest[start + whole.len()..];
        match kind {
            Some(b'#') => open.push((name, flags.contains(name))),
            Some(b'^') => open.push((name, !flags.contains(name))),
            Some(_) => {
                let closed = open.pop().map(|(n, _)| n);
                debug_assert_eq!(closed, Some(name), "unbalanced prompt template");
            }
            None if keeping => out.push_str(vars.get(name).map_or(whole, String::as_str)),
            None => {}
        }
    }
    if open.iter().all(|(_, keep)| *keep) {
        out.push_str(rest);
    }
    out
}

/// The key of a full-access caller holding every capability: what a connection spanning
/// several workspaces is told before it learns its role in each.
const UNRESTRICTED: &str = "full:11:1:full:full:11";

fn level(level: AuthorLevel) -> &'static str {
    match level {
        AuthorLevel::None => "none",
        AuthorLevel::Compose => "compose",
        AuthorLevel::Full => "full",
    }
}

fn bit(b: bool) -> char {
    if b {
        '1'
    } else {
        '0'
    }
}

/// Which generated prompt the caller reads, keyed as `mcpSessionGen.test.ts` generates them.
/// A failed lookup reads as allowed: the prompt only describes, the API still refuses.
pub(crate) async fn prompt_profile(
    db: &DB,
    auth: &crate::db::ApiAuthed,
    w_id: &str,
    access: SessionAccess,
) -> String {
    match access {
        SessionAccess::ReadOnly => return "read_only".to_string(),
        SessionAccess::ReadAndRun => return "read_run".to_string(),
        SessionAccess::Full => {}
    }
    let caps = caller_capabilities(db, w_id, auth)
        .await
        .unwrap_or(RoleCapabilities::FULL);
    let deploy = !matches!(
        check_deploy_rules(w_id, &auth.username, &auth.groups, auth.is_admin, db).await,
        Ok(RuleCheckResult::Blocked(_))
    );
    full_profile(auth.is_admin, deploy, &caps)
}

fn full_profile(is_admin: bool, deploy: bool, caps: &RoleCapabilities) -> String {
    format!(
        "full:{}{}:{}:{}:{}:{}{}",
        bit(is_admin),
        bit(deploy),
        bit(caps.code),
        level(caps.flows),
        level(caps.apps),
        bit(caps.manage_schedules),
        bit(caps.manage_triggers),
    )
}

fn profile_for(profile: &str) -> &'static Profile {
    let parts = &*PARTS;
    // A role no profile covers (full flows without code, which writes refuse) reads as the
    // unrestricted one.
    parts
        .profiles
        .get(profile)
        .or_else(|| parts.profiles.get(UNRESTRICTED))
        .expect("the unrestricted profile is generated")
}

/// The prompt for `profile`, with the caller's username and folder guidance filled in.
fn render(profile: &Profile, username: &str, folder_guidance: &str) -> String {
    let mut vars = profile.vars.clone();
    vars.insert("username".to_string(), username.to_string());
    vars.insert("folder_guidance".to_string(), folder_guidance.to_string());
    render_template(&PARTS.template, &profile.flags(), &vars)
}

/// Folders named in the prompt before the rest are counted rather than listed, as the
/// session does, so a folder-heavy workspace cannot dominate the instructions.
const MAX_LISTED_FOLDERS: usize = 40;

fn folder_list(names: &[&str]) -> String {
    let shown = names
        .iter()
        .take(MAX_LISTED_FOLDERS)
        .map(|n| format!("`f/{n}`"))
        .collect::<Vec<_>>()
        .join(", ");
    if names.len() > MAX_LISTED_FOLDERS {
        format!("{shown} (+{} more)", names.len() - MAX_LISTED_FOLDERS)
    } else {
        shown
    }
}

/// Flags of `EXTERNAL_PROMPT` this file reads itself, which `folder_guidance_follows_the_template`
/// pins: the template shows the folder guidance only under the first, in path conventions that
/// name `create_folder` under the second.
const WRITES_FLAG: &str = "can_write_any_draft";
const CREATE_FOLDER_FLAG: &str = "can_create_folder";

fn folder_guidance(auth: &crate::db::ApiAuthed, profile: &Profile) -> String {
    let flags = profile.flags();
    if !flags.contains(WRITES_FLAG) {
        return String::new();
    }
    let writable: Vec<&str> = auth
        .folders()
        .iter()
        .filter(|(_, write, _)| *write)
        .map(|(name, _, _)| name.as_str())
        .collect();
    let readonly: Vec<&str> = auth
        .folders()
        .iter()
        .filter(|(_, write, _)| !*write)
        .map(|(name, _, _)| name.as_str())
        .collect();

    let guidance = if flags.contains(CREATE_FOLDER_FLAG) {
        &PARTS.folder_guidance.create_folder
    } else {
        &PARTS.folder_guidance.no_create_folder
    };
    let template = match (auth.is_admin(), writable.is_empty(), readonly.is_empty()) {
        (true, false, _) => &guidance.admin,
        (true, true, _) => &guidance.admin_no_folders,
        (false, false, true) => &guidance.member,
        (false, false, false) => &guidance.member_readonly,
        (false, true, true) => &guidance.member_no_folders,
        (false, true, false) => &guidance.member_no_folders_readonly,
    };
    template
        .replace("{{username}}", auth.username())
        .replace("{{writable_folders}}", &folder_list(&writable))
        .replace("{{readonly_folders}}", &folder_list(&readonly))
}

/// The workspace's skills and its admin-written instructions.
async fn appendix(ctx: &Ctx<'_>) -> String {
    let mut text = String::new();
    // Either lookup failing leaves its section out: a client that cannot connect at all
    // is worse than one that connects without the skills list.
    if let Ok(skills) = list_skills(ctx).await {
        if !skills.is_empty() {
            text.push_str(&PARTS.skills_header);
            let lines = skills
                .iter()
                .map(|skill| {
                    PARTS
                        .skill_line
                        .replace("{{skill_path}}", &skill.path)
                        .replace("{{skill_description}}", &skill.description)
                })
                .collect::<Vec<_>>()
                .join("\n");
            text.push_str(&lines);
        }
    }
    if let Ok(info) = ctx.get(&ctx.ws("workspaces/get_copilot_info")).await {
        let workspace = info
            .pointer("/custom_prompts/global")
            .and_then(|v| v.as_str())
            .map(str::trim)
            .filter(|s| !s.is_empty());
        if let Some(workspace) = workspace {
            text.push_str(
                &PARTS
                    .workspace_instructions
                    .replace("{{workspace_instructions}}", workspace),
            );
        }
    }
    text
}

/// The whole prompt, for a connection that reaches one workspace.
pub(crate) async fn session_instructions(ctx: &Ctx<'_>, profile: &str) -> String {
    let profile = profile_for(profile);
    let mut text = render(
        profile,
        ctx.auth.username(),
        &folder_guidance(ctx.auth, profile),
    );
    text.push_str(&appendix(ctx).await);
    text
}

/// The prompt without anything specific to a workspace, for a connection that reaches
/// several: usernames and roles are per workspace, so paths read `u/<username>/...` and a full
/// token reads the unrestricted prompt until `workspace_context` narrows it.
pub(crate) fn generic_session_instructions(access: SessionAccess) -> String {
    render(profile_for(generic_profile(access)), "<username>", "")
}

fn generic_profile(access: SessionAccess) -> &'static str {
    match access {
        SessionAccess::ReadOnly => "read_only",
        SessionAccess::ReadAndRun => "read_run",
        SessionAccess::Full => UNRESTRICTED,
    }
}

/// What `generic_session_instructions(token_access)` leaves out, for one workspace. A role or
/// workspace that narrows the prompt gets its own in full, since its rules replace the general
/// ones; `ctx.access` may be narrower than the token's.
pub(crate) async fn workspace_context(
    ctx: &Ctx<'_>,
    profile: &str,
    token_access: SessionAccess,
) -> String {
    let username = ctx.auth.username();
    let header = format!(
        "Workspace `{}`. Your username here is \"{username}\", so your personal paths are \
         `u/{username}/<name>`.\n",
        ctx.w_id
    );
    let profile = profile_for(profile);
    let folders = folder_guidance(ctx.auth, profile);
    // Roles that differ in name can read the same prompt, so the text decides.
    let general =
        render(profile, "", "") == render(profile_for(generic_profile(token_access)), "", "");
    let body = if general {
        folders.trim_end().to_string()
    } else {
        format!(
            "Your access in this workspace is narrower than the general instructions assume. \
             Here, these rules replace them:\n\n{}",
            render(profile, username, &folders)
        )
    };
    format!(
        "{header}{}{}",
        body.trim_start_matches('\n'),
        appendix(ctx).await
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use sha2::{Digest, Sha256};

    #[test]
    fn folder_guidance_follows_the_template() {
        for (key, profile) in &PARTS.profiles {
            let flags = profile.flags();
            let mut vars = profile.vars.clone();
            vars.insert("folder_guidance".to_string(), "@@folders@@".to_string());
            let text = render_template(&PARTS.template, &flags, &vars);
            assert_eq!(
                text.contains("@@folders@@"),
                flags.contains(WRITES_FLAG),
                "{key}"
            );
            assert_eq!(
                text.contains("create_folder"),
                flags.contains(CREATE_FOLDER_FLAG),
                "{key}"
            );
        }
    }

    /// This renderer reads every profile as `promptTemplate.ts` rendered it when generating.
    #[test]
    fn renders_every_profile_as_the_generator_did() {
        for (key, profile) in &PARTS.profiles {
            let text = render_template(&PARTS.template, &profile.flags(), &profile.vars);
            assert_eq!(
                hex::encode(Sha256::digest(text.as_bytes())),
                PARTS.rendered_sha256[key],
                "{key}"
            );
        }
    }

    /// Every role a caller can hold reads a prompt generated for it, rather than falling back
    /// to the unrestricted one: the keys here and in `mcpSessionGen.test.ts` must agree.
    #[test]
    fn every_valid_role_has_a_generated_prompt() {
        let levels = [AuthorLevel::None, AuthorLevel::Compose, AuthorLevel::Full];
        for deploy in [true, false] {
            assert!(PARTS.profiles.contains_key(&full_profile(
                true,
                deploy,
                &RoleCapabilities::FULL
            )));
            for code in [true, false] {
                for flows in levels {
                    for apps in levels {
                        if !code && (flows == AuthorLevel::Full || apps == AuthorLevel::Full) {
                            continue;
                        }
                        for (manage_schedules, manage_triggers) in
                            [(true, true), (true, false), (false, true), (false, false)]
                        {
                            let caps = RoleCapabilities {
                                code,
                                flows,
                                apps,
                                manage_schedules,
                                manage_triggers,
                                ..RoleCapabilities::FULL
                            };
                            let key = full_profile(false, deploy, &caps);
                            assert!(PARTS.profiles.contains_key(&key), "{key}");
                        }
                    }
                }
            }
        }
        assert!(
            PARTS.profiles.contains_key("read_only") && PARTS.profiles.contains_key("read_run")
        );
    }
}
